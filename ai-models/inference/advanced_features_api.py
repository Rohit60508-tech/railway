@router.post("/validate-resources", summary="Validate Heavy Track Machine Transit & Prevent Ghost Blocks")
def validate_resources_for_block(req: ValidateResourceRequest) -> Dict[str, Any]:
    """Checks transit speed and distance constraints to verify that machinery can reach the block site."""
    try:
        return ResourceFleetBalancer.validate_resource_for_block(
            machine_id=req.machine_id,
            target_km=req.target_km,
            scheduled_start_hour=req.scheduled_start_hour,
        )
    except Exception as e:
        logger.error(f"Error validating resource: {e}")
        raise HTTPException(status_code=500, detail=str(e))


